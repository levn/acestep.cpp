int main(int argc, char ** argv) {
    ace_lm_default_params(&g_lm_params);
    ace_synth_default_params(&g_synth_params);

    const char * host        = "127.0.0.1";
    int          port        = 8080;
    const char * models_dir  = nullptr;
    const char * loras_dir   = nullptr;
    bool         enable_cors = false;

    if (argc < 2) {
        usage(argv[0]);
        return 1;
    }

    for (int i = 1; i < argc; i++) {
        if (!strcmp(argv[i], "--models") && i + 1 < argc) {
            models_dir = argv[++i];
        } else if (!strcmp(argv[i], "--loras") && i + 1 < argc) {
            loras_dir = argv[++i];
        } else if (!strcmp(argv[i], "--max-seq") && i + 1 < argc) {
            g_lm_params.max_seq = atoi(argv[++i]);

            // vae tiling
        } else if (!strcmp(argv[i], "--vae-chunk") && i + 1 < argc) {
            g_synth_params.vae_chunk = atoi(argv[++i]);
        } else if (!strcmp(argv[i], "--vae-overlap") && i + 1 < argc) {
            g_synth_params.vae_overlap = atoi(argv[++i]);
        } else if (!strcmp(argv[i], "--vae-cpu")) {
            g_synth_params.vae_cpu = true;
        } else if (!strcmp(argv[i], "--keep-loaded")) {
            g_keep_loaded = true;

            // output
        } else if (!strcmp(argv[i], "--mp3-bitrate") && i + 1 < argc) {
            g_mp3_kbps = atoi(argv[++i]);

            // server
        } else if (!strcmp(argv[i], "--host") && i + 1 < argc) {
            host = argv[++i];
        } else if (!strcmp(argv[i], "--port") && i + 1 < argc) {
            port = atoi(argv[++i]);
        } else if (!strcmp(argv[i], "--max-batch") && i + 1 < argc) {
            g_max_batch = atoi(argv[++i]);

            // output
        } else if (!strcmp(argv[i], "--output-dir") && i + 1 < argc) {
            g_output_dir = argv[++i];

            // debug
        } else if (!strcmp(argv[i], "--no-fsm")) {
            g_lm_params.use_fsm = false;
        } else if (!strcmp(argv[i], "--no-fa")) {
            g_lm_params.use_fa    = false;
            g_synth_params.use_fa = false;
        } else if (!strcmp(argv[i], "--no-batch-cfg")) {
            g_lm_params.use_batch_cfg = false;
        } else if (!strcmp(argv[i], "--clamp-fp16")) {
            g_lm_params.clamp_fp16    = true;
            g_synth_params.clamp_fp16 = true;
        } else if (!strcmp(argv[i], "--cors")) {
            enable_cors = true;

        } else if (!strcmp(argv[i], "--help") || !strcmp(argv[i], "-h")) {
            usage(argv[0]);
            return 0;
        } else {
            fprintf(stderr, "Unknown option: %s\n", argv[i]);
            usage(argv[0]);
            return 1;
        }
    }

    // --models is required
    if (!models_dir) {
        fprintf(stderr, "[Server] ERROR: --models is required\n");
        usage(argv[0]);
        return 1;
    }

    // stderr capture for SSE /logs (must be after arg parsing so --help prints directly)
    LogCapture log_capture;

    // scan models directory (reads GGUF metadata only)
    fprintf(stderr, "[Server] Scanning models in %s\n", models_dir);
    if (!registry_scan(&g_registry, models_dir)) {
        fprintf(stderr, "[Server] ERROR: no GGUF models found in %s\n", models_dir);
        return 1;
    }

    // scan loras directory (optional)
    if (loras_dir) {
        fprintf(stderr, "[Server] Scanning LoRAs in %s\n", loras_dir);
        registry_scan_loras(&g_registry, loras_dir);
    }

    // validate pipeline
    bool have_lm    = !g_registry.lm.empty();
    bool have_dit   = !g_registry.dit.empty();
    bool have_enc   = !g_registry.text_enc.empty();
    bool have_vae   = !g_registry.vae.empty();
    bool have_synth = have_dit && have_enc && have_vae;

    // partial synth: some components found but pipeline incomplete
    if (!have_synth && (have_dit || have_enc || have_vae)) {
        char missing[64];
        int  n = 0;
        if (!have_dit) {
            n += snprintf(missing + n, sizeof(missing) - n, "%sDiT", n ? ", " : "");
        }
        if (!have_enc) {
            n += snprintf(missing + n, sizeof(missing) - n, "%sText-Enc", n ? ", " : "");
        }
        if (!have_vae) {
            n += snprintf(missing + n, sizeof(missing) - n, "%sVAE", n ? ", " : "");
        }
        if (have_lm) {
            fprintf(stderr, "[Server] WARNING: /synth unavailable, missing: %s\n", missing);
        } else {
            fprintf(stderr, "[Server] ERROR: no usable pipeline, synth missing: %s\n", missing);
            return 1;
        }
    }

    g_max_batch = clamp_int(g_max_batch, 1, MAX_SYNTH_BATCH);
    g_lm_params.max_batch = g_max_batch;

    // init understand params (vae for audio encoding, dit resolved per-request)
    ace_understand_default_params(&g_und_params);
    g_und_params.use_fa  = g_lm_params.use_fa;
    g_und_params.use_fsm = g_lm_params.use_fsm;
    if (have_vae) {
        g_und_params.vae_path = g_registry.vae[0].path.c_str();
    }

    bool have_understand = have_lm && have_dit && have_vae;

    // setup HTTP server
    httplib::Server svr;
    g_svr = &svr;

    // SO_REUSEADDR: allow rebind after TIME_WAIT (normal restart).
    // no SO_REUSEPORT: fail if another process is actively listening.
    svr.set_socket_options([](socket_t sock) {
        int one = 1;
#ifdef _WIN32
        setsockopt(sock, SOL_SOCKET, SO_REUSEADDR, (const char *) &one, sizeof(one));
#else
        setsockopt(sock, SOL_SOCKET, SO_REUSEADDR, &one, sizeof(one));
#endif
    });

    // reject oversized bodies (256 MB: src + ref audio, up to 10min WAV each)
    svr.set_payload_max_length(256 * 1024 * 1024);

    // CORS: allow cross-origin requests when --cors is set
    if (enable_cors) {
        svr.set_default_headers({
            {"Access-Control-Allow-Origin",  "*"},
            {"Access-Control-Allow-Methods", "GET, POST, OPTIONS"},
            {"Access-Control-Allow-Headers", "Content-Type"},
        });
        svr.Options(".*", [](const httplib::Request &, httplib::Response & res) {
            res.status = 204;
        });
    }

    // all endpoints are always registered. handlers return 501 when the
    // backing pipeline has no models in the registry.
    svr.Post("/lm", handle_lm);
    svr.Post("/synth", handle_synth);
    svr.Post("/understand", handle_understand);
    svr.Get("/health", [&](const httplib::Request &, httplib::Response & res) {
        bool gpu_busy = !mtx_gpu.try_lock();
        if (!gpu_busy) {
            mtx_gpu.unlock();
        }

        yyjson_mut_doc * doc  = yyjson_mut_doc_new(NULL);
        yyjson_mut_val * root = yyjson_mut_obj(doc);
        yyjson_mut_doc_set_root(doc, root);
        yyjson_mut_obj_add_str(doc, root, "status", "ok");
        yyjson_mut_obj_add_bool(doc, root, "gpu_busy", gpu_busy);

        yyjson_mut_val * pipelines = yyjson_mut_obj(doc);
        yyjson_mut_obj_add_val(doc, root, "pipelines", pipelines);
        yyjson_mut_obj_add_bool(doc, pipelines, "lm", have_lm);
        yyjson_mut_obj_add_bool(doc, pipelines, "synth", have_synth);
        yyjson_mut_obj_add_bool(doc, pipelines, "understand", have_understand);

        char * json = yyjson_mut_write(doc, 0, NULL);
        yyjson_mut_doc_free(doc);
        res.set_content(json, "application/json");
        free(json);
    });
    svr.Get("/props", handle_props);
    svr.Get("/logs", handle_logs);
    
    // download saved JSON metadata files
    svr.Get("/json/:filename", [](const httplib::Request & req, httplib::Response & res) {
        if (g_output_dir.empty()) {
            json_error(res, 501, "JSON output not configured");
            return;
        }
        auto filename = req.path_params.at("filename");
        // security: only allow alphanumeric, underscore, dash, dot; reject path traversal
        if (filename.find("..") != std::string::npos) {
            json_error(res, 400, "Invalid filename");
            return;
        }
        for (auto c : filename) {
            if (!isalnum(c) && c != '_' && c != '-' && c != '.') {
                json_error(res, 400, "Invalid filename");
                return;
            }
        }
        std::string path = g_output_dir + "/" + filename;
        FILE * f = fopen(path.c_str(), "rb");
        if (!f) {
            json_error(res, 404, "File not found");
            return;
        }
        fseek(f, 0, SEEK_END);
        long size = ftell(f);
        fseek(f, 0, SEEK_SET);
        std::string content(size, 0);
        size_t nread = fread(content.data(), 1, size, f);
        fclose(f);
        if ((long) nread != size) {
            json_error(res, 500, "Failed to read file");
            return;
        }
        res.set_content(content, "application/json");
    });
    
    // list available JSON files
    svr.Get("/jsons", [](const httplib::Request &, httplib::Response & res) {
        if (g_output_dir.empty()) {
            res.set_content("[]", "application/json");
            return;
        }
        yyjson_mut_doc * doc = yyjson_mut_doc_new(NULL);
        yyjson_mut_val * root = yyjson_mut_arr(doc);
        yyjson_mut_doc_set_root(doc, root);
        
        #ifdef _WIN32
        WIN32_FIND_DATAA findData;
        HANDLE hFind = FindFirstFileA((g_output_dir + "/*.json").c_str(), &findData);
        if (hFind != INVALID_HANDLE_VALUE) {
            do {
                yyjson_mut_val * item = yyjson_mut_obj(doc);
                yyjson_mut_obj_add_str(doc, item, "filename", findData.cFileName);
                struct _stat64 st;
                std::string fullpath = g_output_dir + "/" + findData.cFileName;
                if (_stat64(fullpath.c_str(), &st) == 0) {
                    yyjson_mut_obj_add_int(doc, item, "size", st.st_size);
                    yyjson_mut_obj_add_int(doc, item, "mtime", st.st_mtime);
                }
                yyjson_mut_arr_append(root, item);
            } while (FindNextFileA(hFind, &findData));
            FindClose(hFind);
        }
        #else
        DIR * dir = opendir(g_output_dir.c_str());
        if (dir) {
            struct dirent * entry;
            while ((entry = readdir(dir)) != nullptr) {
                std::string name = entry->d_name;
                if (name.length() > 5 && name.substr(name.length() - 5) == ".json") {
                    yyjson_mut_val * item = yyjson_mut_obj(doc);
                    yyjson_mut_obj_add_str(doc, item, "filename", name.c_str());
                    struct stat st;
                    std::string fullpath = g_output_dir + "/" + name;
                    if (stat(fullpath.c_str(), &st) == 0) {
                        yyjson_mut_obj_add_int(doc, item, "size", st.st_size);
                        yyjson_mut_obj_add_int(doc, item, "mtime", st.st_mtime);
                    }
                    yyjson_mut_arr_append(root, item);
                }
            }
            closedir(dir);
        }
        #endif
        
        char * json = yyjson_mut_write(doc, 0, NULL);
        yyjson_mut_doc_free(doc);
        res.set_content(json, "application/json");
        free(json);
    });

    // embedded webui: gzipped single-page app (built by tools/webui/).
    // the browser decompresses transparently via Content-Encoding: gzip.
    // the .gz is committed to git so cloning + cmake + make gives a working UI.
    if (index_html_gz_len > 0) {
        svr.Get("/", [](const httplib::Request & req, httplib::Response & res) {
            if (req.get_header_value("Accept-Encoding").find("gzip") == std::string::npos) {
                res.set_content("Error: gzip is not supported by this browser", "text/plain");
            } else {
                res.set_header("Content-Encoding", "gzip");
                res.set_header("Cache-Control", "no-store, max-age=0");
                res.set_header("Pragma", "no-cache");
                res.set_content(reinterpret_cast<const char *>(index_html_gz), index_html_gz_len,
                                "text/html; charset=utf-8");
            }
        });
    }

    // graceful shutdown on SIGINT/SIGTERM
#ifdef _WIN32
    signal(SIGINT, on_signal);
    signal(SIGTERM, on_signal);
#else
    struct sigaction sa = {};
    sa.sa_handler       = on_signal;
    sigemptyset(&sa.sa_mask);
    sigaction(SIGINT, &sa, nullptr);
    sigaction(SIGTERM, &sa, nullptr);
#endif

    fprintf(stderr, "[Server] acestep.cpp %s\n", ACE_VERSION);
    fprintf(stderr, "[Server] Listening on %s:%d\n", host, port);
    fprintf(stderr, "[Server] Pipelines:%s%s%s\n", have_lm ? " /lm" : "", have_synth ? " /synth" : "",
            have_understand ? " /understand" : "");
    fprintf(stderr, "[Server] Models: %zu LM, %zu Text-Enc, %zu DiT, %zu VAE, %zu LoRA\n", g_registry.lm.size(),
            g_registry.text_enc.size(), g_registry.dit.size(), g_registry.vae.size(), g_registry.loras.size());
    if (!svr.listen(host, port)) {
        fprintf(stderr, "[Server] FATAL: cannot bind %s:%d\n", host, port);
    }

    // cleanup (all _free functions handle NULL)
    fprintf(stderr, "[Server] Shutting down...\n");
    ace_understand_free(g_ctx_understand);
    ace_synth_free(g_ctx_synth);
    ace_lm_free(g_ctx_lm);
    fprintf(stderr, "[Server] Done\n");

    return 0;
}

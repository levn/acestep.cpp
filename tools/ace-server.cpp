// log capture: intercept stderr via pipe, forward to terminal + ring buffer.
// SSE clients connect to /logs and receive lines in real time.
#define LOG_RING_BITS 9
#define LOG_RING_SIZE (1 << LOG_RING_BITS)
#define LOG_RING_MASK (LOG_RING_SIZE - 1)

static std::mutex              mtx_log;
static std::condition_variable cv_log;
static std::string             log_ring[LOG_RING_SIZE];
static uint64_t                log_seq = 0;

static int g_real_stderr_fd = -1;
static int g_pipe_read_fd   = -1;

static void setup_log_capture() {
    g_real_stderr_fd = fd_dup(STDERR_FILENO);
    int pipefd[2];
    if (fd_pipe(pipefd) != 0) {
        g_real_stderr_fd = -1;
        return;
    }
    g_pipe_read_fd = pipefd[0];
    fd_dup2(pipefd[1], STDERR_FILENO);
    fd_close(pipefd[1]);
}

// reader thread: drain pipe, forward to real stderr, push lines to ring.
// exits when the write end of the pipe is closed (fd_dup2 restores real stderr).
static void log_reader_main() {
    char        buf[4096];
    std::string partial;
    for (;;) {
        int n = fd_read(g_pipe_read_fd, buf, sizeof(buf));
        if (n <= 0) {
            break;
        }
        fd_write(g_real_stderr_fd, buf, (size_t) n);
        partial.append(buf, (size_t) n);
        size_t pos;
        while ((pos = partial.find('\n')) != std::string::npos) {
            std::lock_guard<std::mutex> lock(mtx_log);
            log_ring[log_seq & LOG_RING_MASK] = partial.substr(0, pos);
            log_seq++;
            cv_log.notify_all();
            partial.erase(0, pos + 1);
        }
    }
    if (!partial.empty()) {
        std::lock_guard<std::mutex> lock(mtx_log);
        log_ring[log_seq & LOG_RING_MASK] = std::move(partial);
        log_seq++;
        cv_log.notify_all();
    }
    fd_close(g_pipe_read_fd);
}

static void teardown_log_capture() {
    if (g_real_stderr_fd < 0) {
        return;
    }
    fflush(stderr);
    fd_dup2(g_real_stderr_fd, STDERR_FILENO);
    // g_real_stderr_fd stays open: the reader thread writes to it
}

// RAII: captures stderr on construction, restores + joins reader on destruction.
// safe on any exit path (early arg errors, model load failures, normal shutdown).
struct LogCapture {
    std::thread reader;

    LogCapture() {
        setup_log_capture();
        reader = std::thread(log_reader_main);
    }

    ~LogCapture() {
        teardown_log_capture();
        cv_log.notify_all();
        if (reader.joinable()) {
            reader.join();
        }

        // reader is done draining the pipe, safe to close
        if (g_real_stderr_fd >= 0) {
            fd_close(g_real_stderr_fd);
            g_real_stderr_fd = -1;
        }
    }
};

// GET /logs: SSE stream of stderr lines.
// sends backlog (up to LOG_RING_SIZE) then streams new lines in real time.
static void handle_logs(const httplib::Request &, httplib::Response & res) {
    res.set_header("Cache-Control", "no-cache");
    res.set_header("X-Accel-Buffering", "no");
    res.set_chunked_content_provider(
        "text/event-stream", [cursor = uint64_t(0), init = false](size_t, httplib::DataSink & sink) mutable -> bool {
            std::unique_lock<std::mutex> lock(mtx_log);
            if (!init) {
                uint64_t avail = log_seq < LOG_RING_SIZE ? log_seq : (uint64_t) LOG_RING_SIZE;
                cursor         = log_seq - avail;
                while (cursor < log_seq) {
                    std::string ev = "data: " + log_ring[cursor & LOG_RING_MASK] + "\n\n";
                    cursor++;
                    lock.unlock();
                    if (!sink.write(ev.c_str(), ev.size())) {
                        return false;
                    }
                    lock.lock();
                }
                init = true;
            }
            cv_log.wait_for(lock, std::chrono::seconds(2));
            while (cursor < log_seq) {
                std::string ev = "data: " + log_ring[cursor & LOG_RING_MASK] + "\n\n";
                cursor++;
                lock.unlock();
                if (!sink.write(ev.c_str(), ev.size())) {
                    return false;
                }
                lock.lock();
            }
            return true;
        });
}

// cancel trampoline: bridges httplib's is_connection_closed to our cancel callback.
// data points to the std::function<bool()> from httplib::Request.
static bool server_cancel(void * data) {
    auto * fn = (const std::function<bool()> *) data;
    return (*fn)();
}

// helper: set a JSON error response
static void json_error(httplib::Response & res, int status, const char * msg) {
    yyjson_mut_doc * doc  = yyjson_mut_doc_new(NULL);
    yyjson_mut_val * root = yyjson_mut_obj(doc);
    yyjson_mut_doc_set_root(doc, root);
    yyjson_mut_obj_add_str(doc, root, "error", msg);
    char * json = yyjson_mut_write(doc, 0, NULL);
    yyjson_mut_doc_free(doc);
    res.status = status;
    res.set_content(json, "application/json");
    free(json);
}

// helper: 503 when GPU is busy
static void json_busy(httplib::Response & res) {
    res.status = 503;
    res.set_header("Retry-After", "5");
    res.set_content("{\"error\":\"Server busy\"}", "application/json");
}

// resolve model name: explicit request > already loaded > first in bucket
static std::string resolve_name(const std::vector<ModelEntry> & bucket,
                                const std::string &             requested,
                                const std::string &             loaded) {
    if (!requested.empty()) {
        return requested;
    }
    if (!loaded.empty()) {
        return loaded;
    }
    if (!bucket.empty()) {
        return bucket[0].name;
    }
    return "";
}

// server-side routing fields parsed from JSON (not part of AceRequest)
struct ServerFields {
    std::string synth_model;
    std::string lm_model;
    std::string lora;
    float       lora_scale;
};

static void parse_server_fields(const char * json, ServerFields * sf) {
    sf->synth_model = "";
    sf->lm_model    = "";
    sf->lora        = "";
    sf->lora_scale  = 1.0f;

    yyjson_doc * doc = yyjson_read(json, strlen(json), 0);
    if (!doc) {
        return;
    }
    yyjson_val * root = yyjson_doc_get_root(doc);
    if (!root) {
        yyjson_doc_free(doc);
        return;
    }

    // for arrays, take server fields from the first element
    yyjson_val * obj = root;
    if (yyjson_is_arr(root)) {
        obj = yyjson_arr_get_first(root);
    }
    if (!obj || !yyjson_is_obj(obj)) {
        yyjson_doc_free(doc);
        return;
    }

    yyjson_val * v;
    if ((v = yyjson_obj_get(obj, "synth_model")) && yyjson_is_str(v)) {
        sf->synth_model = yyjson_get_str(v);
    }
    if ((v = yyjson_obj_get(obj, "lm_model")) && yyjson_is_str(v)) {
        sf->lm_model = yyjson_get_str(v);
    }
    if ((v = yyjson_obj_get(obj, "lora")) && yyjson_is_str(v)) {
        sf->lora = yyjson_get_str(v);
    }
    if ((v = yyjson_obj_get(obj, "lora_scale")) && yyjson_is_num(v)) {
        sf->lora_scale = (float) yyjson_get_num(v);
    }

    yyjson_doc_free(doc);
}

// load LM. frees understand (shared pointers become invalid) but does not rebuild it.
// returns false on failure (caller returns 500).
static bool ensure_lm(const std::string & name) {
    if (g_ctx_lm && g_loaded_lm == name) {
        return true;
    }

    const ModelEntry * entry = registry_find(g_registry.lm, name.c_str());
    if (!entry) {
        fprintf(stderr, "[Server] LM not found: %s\n", name.c_str());
        return false;
    }

    // understand holds shared LM pointers, free before LM reload
    ace_understand_free(g_ctx_understand);
    g_ctx_understand = nullptr;
    g_loaded_und_dit.clear();
    ace_lm_free(g_ctx_lm);
    g_ctx_lm = nullptr;

    // load new
    fprintf(stderr, "[Server] Loading LM: %s\n", name.c_str());
    g_lm_params.model_path = entry->path.c_str();
    g_ctx_lm               = ace_lm_load(&g_lm_params);
    if (!g_ctx_lm) {
        fprintf(stderr, "[Server] FATAL: LM load failed\n");
        g_loaded_lm.clear();
        return false;
    }

    g_loaded_lm = name;
    return true;
}

// load understand pipeline (LM + tokenizer from DiT).
// reloads when LM or DiT changes. tokenizer weights differ between DiT variants.
static bool ensure_understand(const std::string & lm_name, const std::string & dit_name) {
    if (!ensure_lm(lm_name)) {
        return false;
    }

    // already loaded with the same DiT tokenizer
    if (g_ctx_understand && g_loaded_und_dit == dit_name) {
        return true;
    }

    // update dit_path for the tokenizer
    const ModelEntry * dit = registry_find(g_registry.dit, dit_name.c_str());
    if (dit) {
        g_und_params.dit_path = dit->path.c_str();
    }

    // (re)build understand with shared LM
    ace_understand_free(g_ctx_understand);
    g_ctx_understand = nullptr;

    g_und_params.shared_model = ace_lm_get_model(g_ctx_lm);
    g_und_params.shared_bpe   = ace_lm_get_bpe(g_ctx_lm);
    g_ctx_understand          = ace_understand_load(&g_und_params);
    if (!g_ctx_understand) {
        fprintf(stderr, "[Server] FATAL: understand load failed\n");
        g_loaded_und_dit.clear();
        return false;
    }

    g_loaded_und_dit = dit_name;
    return true;
}

// load synth pipeline (DiT + LoRA + text-enc + VAE). frees previous context first.
// returns false on failure (caller returns 500).
static bool ensure_synth(const std::string & dit_name, const std::string & lora_name, float lora_scale) {
    if (g_ctx_synth && g_loaded_dit == dit_name && g_loaded_lora == lora_name && g_loaded_lora_scale == lora_scale) {
        return true;
    }

    // need text-encoder + vae singletons
    if (g_registry.text_enc.empty() || g_registry.vae.empty()) {
        fprintf(stderr, "[Server] Missing Text-Enc or VAE in registry\n");
        return false;
    }

    const ModelEntry * dit = registry_find(g_registry.dit, dit_name.c_str());
    if (!dit) {
        fprintf(stderr, "[Server] DiT not found: %s\n", dit_name.c_str());
        return false;
    }

    // unload old
    ace_synth_free(g_ctx_synth);
    g_ctx_synth = nullptr;

    // set paths
    g_synth_params.text_encoder_path = g_registry.text_enc[0].path.c_str();
    g_synth_params.dit_path          = dit->path.c_str();
    g_synth_params.vae_path          = g_registry.vae[0].path.c_str();

    // resolve lora
    if (!lora_name.empty()) {
        const LoraEntry * lora = registry_find_lora(g_registry, lora_name.c_str());
        if (!lora) {
            fprintf(stderr, "[Server] LoRA not found: %s\n", lora_name.c_str());
            g_loaded_dit.clear();
            g_loaded_lora.clear();
            return false;
        }
        g_synth_params.lora_path  = lora->path.c_str();
        g_synth_params.lora_scale = lora_scale;
    } else {
        g_synth_params.lora_path  = nullptr;
        g_synth_params.lora_scale = 1.0f;
    }

    fprintf(stderr, "[Server] Loading synth: DiT=%s%s%s\n", dit_name.c_str(),
            lora_name.empty() ? "" : " LoRA=", lora_name.c_str());
    g_ctx_synth = ace_synth_load(&g_synth_params);
    if (!g_ctx_synth) {
        fprintf(stderr, "[Server] FATAL: synth load failed\n");
        g_loaded_dit.clear();
        g_loaded_lora.clear();
        return false;
    }

    g_loaded_dit        = dit_name;
    g_loaded_lora       = lora_name;
    g_loaded_lora_scale = lora_scale;
    return true;
}

// try to acquire GPU mutex. returns lock on success, empty lock on failure (sets 503).
static std::unique_lock<std::mutex> try_gpu_lock(httplib::Response & res) {
    std::unique_lock<std::mutex> lock(mtx_gpu, std::try_to_lock);
    if (!lock.owns_lock()) {
        json_busy(res);
    }
    return lock;
}

// conditionally unload LM pipeline (respects --keep-loaded)
static void maybe_unload_lm() {
    if (g_keep_loaded) {
        return;
    }
    ace_understand_free(g_ctx_understand);
    g_ctx_understand = nullptr;
    ace_lm_free(g_ctx_lm);
    g_ctx_lm = nullptr;
    g_loaded_lm.clear();
    g_loaded_und_dit.clear();
}

// conditionally unload synth pipeline (respects --keep-loaded)
static void maybe_unload_synth() {
    if (g_keep_loaded) {
        return;
    }
    ace_synth_free(g_ctx_synth);
    g_ctx_synth = nullptr;
    g_loaded_dit.clear();
    g_loaded_lora.clear();
}

// clamp value to [lo, hi]
static int clamp_int(int v, int lo, int hi) {
    return v < lo ? lo : (v > hi ? hi : v);
}

// generate a unique ID: YYYYMMDD-HHMMSS-XXXX (timestamp + 4 random hex chars)
static std::string generate_id() {
    char   buf[64];
    time_t now = time(nullptr);
    struct tm tm_buf;
#ifdef _WIN32
    localtime_s(&tm_buf, &now);
#else
    localtime_r(&now, &tm_buf);
#endif
    uint32_t r = std::random_device{}();
    snprintf(buf, sizeof(buf), "%04d%02d%02d-%02d%02d%02d-%04x", tm_buf.tm_year + 1900, tm_buf.tm_mon + 1,
             tm_buf.tm_mday, tm_buf.tm_hour, tm_buf.tm_min, tm_buf.tm_sec, r & 0xFFFF);
    return buf;
}

// build a generation JSON: AceRequest fields + generation_id + model routing info
static std::string build_generation_json(const AceRequest * r, const std::string & gen_id,
                                         const std::string & dit_name, const std::string & lm_name,
                                         const ServerFields & sf) {
    // start from sparse AceRequest JSON
    std::string base = request_to_json(r);
    yyjson_doc * doc  = yyjson_read(base.c_str(), base.size(), 0);
    yyjson_mut_doc * mdoc = yyjson_doc_mut_copy(doc, NULL);
    yyjson_doc_free(doc);
    yyjson_mut_val * root = yyjson_mut_doc_get_root(mdoc);

    // add generation metadata
    yyjson_mut_obj_add_str(mdoc, root, "generation_id", gen_id.c_str());

    // add resolved model names
    if (!dit_name.empty()) {
        yyjson_mut_obj_add_str(mdoc, root, "synth_model", dit_name.c_str());
    }
    if (!lm_name.empty()) {
        yyjson_mut_obj_add_str(mdoc, root, "lm_model", lm_name.c_str());
    }
    if (!sf.lora.empty()) {
        yyjson_mut_obj_add_str(mdoc, root, "lora", sf.lora.c_str());
        yyjson_mut_obj_add_real(mdoc, root, "lora_scale", sf.lora_scale);
    }

    yyjson_write_flag flags = YYJSON_WRITE_PRETTY | YYJSON_WRITE_PRETTY_TWO_SPACES | YYJSON_WRITE_FP_TO_FIXED(2);
    size_t len;
    char * json = yyjson_mut_write(mdoc, flags | YYJSON_WRITE_NEWLINE_AT_END, &len);
    yyjson_mut_doc_free(mdoc);
    std::string result(json, len);
    free(json);
    return result;
}

